"""GE STARR mark (gestarr/brand/mark.svg, from the website's public/brand) → triangle mesh for the app bar badge.

Usage (needs svgelements and shapely >= 2.1):
    python gestarr/mark_mesh.py gestarr/brand/mark.svg > assets/icons/ui/source/gestarr_mark.rs
"""
import sys, svgelements, shapely
from shapely.geometry import Polygon
from shapely.ops import unary_union
svg = svgelements.SVG.parse(sys.argv[1])
polys = []
for e in svg.elements():
    if isinstance(e, svgelements.Path):
        pts = [(p.x, p.y) for p in (e.point(i / 400) for i in range(400))]
        polys.append(Polygon(pts).buffer(0))
shape = unary_union(polys)
minx, miny, maxx, maxy = shape.bounds
cx, cy, s = (minx + maxx) / 2, (miny + maxy) / 2, max(maxx - minx, maxy - miny)
tris = shapely.constrained_delaunay_triangles(shapely.simplify(shape, 0.15))
verts, idx, seen = [], [], {}
area = 0.0
for t in tris.geoms:
    area += t.area
    for x, y in list(t.exterior.coords)[:3]:
        k = (round((x - cx) / s, 4), round((y - cy) / s, 4))
        if k not in seen:
            seen[k] = len(verts); verts.append(k)
        idx.append(seen[k])
print(f"// {len(verts)} vertices, {len(idx)//3} triangles; area check {area/shape.area:.4f}", file=sys.stderr)
out = ["/// GE STARR mark (four G shapes, the website's public/brand/mark.svg), as triangles: centred, unit size, y down.",
       "/// Generated by gestarr/mark_mesh.py; do not edit by hand.",
       f"pub const MARK_VERTS: [[f32; 2]; {len(verts)}] = ["]
out += ["    " + " ".join(f"[{x}, {y}]," for x, y in verts[i:i+6]) for i in range(0, len(verts), 6)]
out += ["];", f"pub const MARK_TRIS: [u16; {len(idx)}] = ["]
out += ["    " + " ".join(f"{v}," for v in idx[i:i+20]) for i in range(0, len(idx), 20)]
out += ["];"]
print("\n".join(out))
